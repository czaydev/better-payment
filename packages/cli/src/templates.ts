/**
 * The files `init` writes.
 *
 * The singleton and the adapter mounting code follow the integration docs
 * (`apps/web/content/docs/integrations/nextjs.mdx` and `frameworks.mdx`) so a
 * generated project looks exactly like the documented setup: a lazy
 * `betterPayment()`, a catch-all route, and the framework's own adapter.
 *
 * Only the config file is shared by every framework. The route is framework
 * specific and imports the config with a relative path (Next.js App Router uses
 * the `@/lib/payment` alias from the docs).
 */
import { relativeImport, type Framework, type ProjectInfo } from './detect';
import { PROVIDER_SPECS } from './provider-specs';

export interface TemplateContext {
  project: ProjectInfo;
  providers: string[];
  basePath: string;
  configPath: string;
  routePath: string;
}

function providerCall(id: string): string {
  const spec = PROVIDER_SPECS[id];
  const fields = spec.fields
    .map((field) => `${field.field}: process.env.${field.env}!`)
    .join(',\n        ');
  return `${spec.factory}: ${spec.factory}({\n        ${fields},\n      })`;
}

/** `lib/payment.ts`: lazy singleton, exported handler options for `doctor` */
export function renderConfig(context: TemplateContext): string {
  const imports = ['betterPayment', ...context.providers.map((id) => PROVIDER_SPECS[id].factory)];
  const providers = context.providers.map((id) => `      ${providerCall(id)},`).join('\n');
  return `// Generated by \`better-payment init\`. Server-only: never import this file from a Client Component.
import {
  ${imports.join(',\n  ')},
  type BetterPaymentHandlerOptions,
} from 'better-payment';

/**
 * Sandbox hosts by default; \`next build\` and tests do not need live credentials
 * because the payment object is created on the first request.
 */
export const mode =
  process.env.PAYMENT_MODE === 'production'
    ? 'production'
    : process.env.NODE_ENV === 'production'
      ? 'production'
      : 'sandbox';

/**
 * What the HTTP handler exposes. Keep this list small: privileged actions
 * (refund, cancel, capture, void, cards/*) also require an \`authorize\` hook.
 * Callbacks and 3D Secure returns must stay reachable: they are verified with
 * your credentials by the provider itself.
 */
export const handlerOptions: BetterPaymentHandlerOptions = {
  allowedActions: ['payment/init-3ds', 'payment/complete-3ds', 'callback'],
  // Amounts must never come from the browser. Set the price, basket and buyer
  // from your database here (see the handler docs):
  // transformRequest: async (ctx) => buildPaymentRequestFromOrder(ctx.body?.orderId),
  // Deduplicate provider callbacks with a shared store when you run more than
  // one instance. The default is an in-memory store, per process:
  // idempotency: { store: new RedisIdempotencyStore(process.env.REDIS_URL!) },
};

const createPayment = () =>
  betterPayment({
    mode,
    providers: {
${providers}
    },
    handler: handlerOptions,
  });

let instance: ReturnType<typeof createPayment> | undefined;

/** The singleton, created on first use so \`next build\` works without env vars. */
export const getBetterPayment = () => (instance ??= createPayment());
`;
}

function nextAppRoute(_context: TemplateContext): string {
  // Exactly the docs' route handler: `@/lib/payment` is the alias create-next-app
  // configures, in both the `src` and the root layout.
  return `import { toNextJsHandler } from 'better-payment/next';
import { getBetterPayment } from '@/lib/payment';

export const { GET, POST } = toNextJsHandler(getBetterPayment);
`;
}

function expressRoute(context: TemplateContext): string {
  const configImport = relativeImport(dirOf(context.routePath), context.configPath).replace(
    /\.(ts|js)$/,
    ''
  );
  return `import { Router } from 'express';
import { toExpressHandler } from 'better-payment/express';
import { getBetterPayment } from '${configImport}';

/**
 * Mount the router once in your app:
 *
 *   import { paymentRoutes } from './routes/payment';
 *   app.use(paymentRoutes);
 */
export const paymentRoutes = Router().all('${context.basePath}/*path', toExpressHandler(getBetterPayment));
`;
}

function fastifyRoute(context: TemplateContext): string {
  const configImport = relativeImport(dirOf(context.routePath), context.configPath).replace(
    /\.(ts|js)$/,
    ''
  );
  return `import type { FastifyInstance } from 'fastify';
import { toFastifyPlugin } from 'better-payment/fastify';
import { getBetterPayment } from '${configImport}';

/** Register once: \`await app.register(paymentPlugin)\` */
export const paymentPlugin = async (app: FastifyInstance) => {
  await app.register(toFastifyPlugin(getBetterPayment), { prefix: '${context.basePath}' });
};
`;
}

function honoRoute(context: TemplateContext): string {
  const configImport = relativeImport(dirOf(context.routePath), context.configPath).replace(
    /\.(ts|js)$/,
    ''
  );
  return `import { Hono } from 'hono';
import { toHonoHandler } from 'better-payment/hono';
import { getBetterPayment } from '${configImport}';

/** Mount once: \`app.route('/', paymentRoutes)\` */
export const paymentRoutes = new Hono();

paymentRoutes.all('${context.basePath}/*', toHonoHandler(getBetterPayment));
`;
}

function elysiaRoute(context: TemplateContext): string {
  const configImport = relativeImport(dirOf(context.routePath), context.configPath).replace(
    /\.(ts|js)$/,
    ''
  );
  return `import { Elysia } from 'elysia';
import { toElysiaHandler } from 'better-payment/elysia';
import { getBetterPayment } from '${configImport}';

/** Mount once: \`app.use(paymentRoutes)\` */
export const paymentRoutes = new Elysia().all('${context.basePath}/*', toElysiaHandler(getBetterPayment), {
  parse: 'none',
});
`;
}

function reactRouterRoute(context: TemplateContext): string {
  const configImport = relativeImport(dirOf(context.routePath), context.configPath).replace(
    /\.(ts|js)$/,
    ''
  );
  return `import { toReactRouterHandler } from 'better-payment/react-router';
import { getBetterPayment } from '${configImport}';

export const { loader, action } = toReactRouterHandler(getBetterPayment);
`;
}

function nodeRoute(context: TemplateContext): string {
  const configImport = relativeImport(dirOf(context.routePath), context.configPath).replace(
    /\.(ts|js)$/,
    ''
  );
  return `import { createServer } from 'node:http';
import { toNodeHandler } from 'better-payment/express';
import { getBetterPayment } from '${configImport}';

const port = Number(process.env.PORT ?? 3000);

createServer(toNodeHandler(getBetterPayment)).listen(port, () => {
  console.log(\`Payment server on http://localhost:\${port}\`);
  console.log(\`Health:         http://localhost:\${port}${context.basePath}/health\`);
});
`;
}

function nextPagesRoute(context: TemplateContext): string {
  const configImport = relativeImport(dirOf(context.routePath), context.configPath).replace(
    /\.(ts|js)$/,
    ''
  );
  return `import { toNodeHandler } from 'better-payment/express';
import { getBetterPayment } from '${configImport}';

/** Next.js Pages Router API route (Node.js runtime only) */
export default toNodeHandler(getBetterPayment);
`;
}

/** Directory part of a POSIX-style repo path */
function dirOf(path: string): string {
  const index = path.lastIndexOf('/');
  return index === -1 ? '' : path.slice(0, index);
}

const ROUTE_RENDERERS: Record<Framework, (context: TemplateContext) => string> = {
  'next-app': nextAppRoute,
  'next-pages': nextPagesRoute,
  express: expressRoute,
  fastify: fastifyRoute,
  hono: honoRoute,
  elysia: elysiaRoute,
  'react-router': reactRouterRoute,
  node: nodeRoute,
};

export function renderRoute(context: TemplateContext): string {
  return ROUTE_RENDERERS[context.project.framework](context);
}

/** `.env.example`: names only, never values */
export function renderEnvExample(context: TemplateContext): string {
  const lines = [
    '# Copy to .env.local (Next.js) or .env and fill in the sandbox credentials.',
    '# Never commit this file with real values. PAYMENT_MODE defaults to sandbox.',
    'PAYMENT_MODE=sandbox',
    '',
  ];
  for (const id of context.providers) {
    const spec = PROVIDER_SPECS[id];
    lines.push(`# ${id}`);
    for (const field of spec.fields) {
      lines.push(`${field.env}=your-${field.env.toLowerCase().replace(/_/g, '-')}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

/** Short per-framework note printed by `init` */
export function mountHint(context: TemplateContext): string {
  switch (context.project.framework) {
    case 'next-app':
      return `The route is at ${context.routePath}; Next.js picks it up automatically.`;
    case 'express':
      return `Import { paymentRoutes } from './routes/payment' and app.use(paymentRoutes).`;
    case 'fastify':
      return `Import { paymentPlugin } and await app.register(paymentPlugin).`;
    case 'hono':
      return `Import { paymentRoutes } and app.route('/', paymentRoutes).`;
    case 'elysia':
      return `Import { paymentRoutes } and app.use(paymentRoutes).`;
    case 'react-router':
      return `Add ${context.routePath} as a splat resource route.`;
    case 'next-pages':
      return `The route lives at ${context.routePath}; keep the Node.js runtime.`;
    default:
      return `Run ${context.routePath} with your bundler or node --experimental-strip-types.`;
  }
}
